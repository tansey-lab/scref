"""Spatial bleed analysis kernels.

Molecular bleed: transcripts generated by a nearby cell of type T_source ending
up inside a cell of type T_sink (e.g. via diffusion). Bleed is measured as a
function of spatial distance to the nearest source-type cell, using the SAME
marker and wrong-gene definitions that drive the contamination metrics -- the
"eligible" genes for a (source, sink) pair are ``markers[source] & wrong[sink]``
(source markers that are also contamination signatures for the sink).

These are stateless kernels operating on plain inputs (a spatial AnnData, a
label array, the marker/wrong dicts, coordinates). They are normally reached
via ``scRNAseqReference.bleed_scan`` / ``bleed_null_comparison``, which supply
the reference's own markers and wrong-genes; exposed here for standalone use.

Distance units follow the coordinate columns (microns for Xenium). All
``max_dist`` / ``r`` parameters are in those units.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Sequence, Set, Tuple

import numpy as np
import pandas as pd
from anndata import AnnData
from scipy.sparse import issparse
from scipy.spatial import cKDTree

DEFAULT_COORD_KEYS = ("x_centroid", "y_centroid")

_SCAN_COLUMNS = [
    "source_type", "sink_type", "sink_cell_row", "distance",
    "eligible_counts", "sink_total_tx", "n_eligible_markers",
    "n_sink_cells_total",
]


def _coords(adata: AnnData, coord_keys: Sequence[str]) -> np.ndarray:
    for c in coord_keys:
        if c not in adata.obs.columns:
            raise ValueError(
                f"spatial adata.obs must have coordinate columns {tuple(coord_keys)}; "
                f"missing {c!r}. Present: {list(adata.obs.columns)}")
    return adata.obs[list(coord_keys)].values.astype(float)


def bleed_scan(
    adata: AnnData,
    group_labels: np.ndarray,
    markers: Dict[str, Set[str]],
    wrong: Dict[str, Set[str]],
    *,
    max_dist: float = 40.0,
    min_sink_cells: int = 50,
    coord_keys: Sequence[str] = DEFAULT_COORD_KEYS,
) -> pd.DataFrame:
    """For every (source_type, sink_type) pair, for every sink cell with a
    source-type neighbor within ``max_dist``, record its distance to the nearest
    source cell and its count of eligible genes (``markers[source] & wrong[sink]``).

    One row per (source, sink, sink-cell) triple. Cells with no source-type
    neighbor within ``max_dist`` are excluded for that pair (their bleed at any
    r in (0, max_dist] is zero), but they still count toward
    ``n_sink_cells_total`` -- the class-balanced denominator for per-type means.

    Columns: source_type, sink_type, sink_cell_row, distance, eligible_counts,
    sink_total_tx, n_eligible_markers, n_sink_cells_total. ``sink_cell_row`` is
    a positional index into ``adata``.
    """
    X = adata.X
    if issparse(X):
        X = X.tocsr()
    X_csc = X.tocsc() if issparse(X) else X

    gene_to_idx = {g: i for i, g in enumerate(adata.var_names)}
    xy = _coords(adata, coord_keys)
    sink_types_arr = np.asarray(group_labels)

    total_per_cell = (np.asarray(X.sum(axis=1)).flatten()
                      if issparse(X) else X.sum(axis=1))

    included_types = sorted([t for t, ms in markers.items() if len(ms) > 0])

    # Per-type KDTrees for source roles (need >= 2 cells to build a tree).
    trees = {}
    for t in included_types:
        mask = sink_types_arr == t
        if mask.sum() < 2:
            continue
        trees[t] = cKDTree(xy[mask])

    def _sum_cols(cols):
        if len(cols) == 0:
            return np.zeros(X_csc.shape[0])
        sub = X_csc[:, cols]
        return (np.asarray(sub.sum(axis=1)).flatten()
                if issparse(sub) else sub.sum(axis=1))

    rows = []
    for src in included_types:
        if src not in trees:
            continue
        src_markers = markers[src]

        non_src_mask = sink_types_arr != src
        non_src_idx = np.where(non_src_mask)[0]
        if non_src_idx.size == 0:
            continue
        dist_to_src, _ = trees[src].query(xy[non_src_idx], k=1)
        abs_dist = np.full(X_csc.shape[0], np.nan)
        abs_dist[non_src_idx] = dist_to_src

        for sink in included_types:
            if sink == src:
                continue
            sink_cells_all = np.where(sink_types_arr == sink)[0]
            if sink_cells_all.size < min_sink_cells:
                continue

            wrong_sink = wrong.get(sink, set())
            eligible_genes = [g for g in src_markers if g in wrong_sink]
            if len(eligible_genes) == 0:
                continue
            elig_cols = [gene_to_idx[g] for g in eligible_genes
                         if g in gene_to_idx]
            if len(elig_cols) == 0:
                continue
            elig_counts_all = _sum_cols(elig_cols)

            d = abs_dist[sink_cells_all]
            c = elig_counts_all[sink_cells_all]
            t = total_per_cell[sink_cells_all]

            keep = np.isfinite(d) & (d < max_dist)
            if not keep.any():
                continue

            rows.append(pd.DataFrame({
                "source_type": src,
                "sink_type": sink,
                "sink_cell_row": sink_cells_all[keep],
                "distance": d[keep].astype(np.float32),
                "eligible_counts": c[keep].astype(np.float32),
                "sink_total_tx": t[keep].astype(np.float32),
                "n_eligible_markers": np.int32(len(eligible_genes)),
                "n_sink_cells_total": np.int32(sink_cells_all.size),
            }))

    if not rows:
        return pd.DataFrame(columns=_SCAN_COLUMNS)
    return pd.concat(rows, ignore_index=True)


# =============================================================================
# Aggregations on a bleed-scan DataFrame (no reference dependency)
# =============================================================================

def bleed_cumulative(
    bleed: pd.DataFrame,
    *,
    r_grid: Optional[np.ndarray] = None,
    max_dist: float = 40.0,
    groupby: Optional[str] = None,
    normalize: bool = False,
    direction: str = "sink",
) -> pd.DataFrame:
    """Cumulative bleed curve B(r), class-balanced per cell type.

    B(r) = (1 / n_denom) * sum over rows with distance <= r of value, where
    value is ``eligible_counts`` (or ``eligible_counts / sink_total_tx`` if
    ``normalize``). For direction='sink' the denominator is ``n_sink_cells_total``
    (all cells of the sink type); for 'source' it's the count of distinct
    non-source cells observed for that source.

    Returns columns (r, cum_mean, n_denom, [group_col]).
    """
    if r_grid is None:
        r_grid = np.linspace(0.0, max_dist, 200)
    if bleed.empty:
        return pd.DataFrame(columns=["r", "cum_mean", "n_denom"])
    if direction not in ("sink", "source"):
        raise ValueError(f"direction must be 'sink' or 'source', got {direction!r}")

    default_group_col = {"sink": "sink_type", "source": "source_type"}[direction]
    group_col = groupby if groupby is not None else default_group_col

    val = bleed["eligible_counts"].values.astype(float)
    if normalize:
        tot = bleed["sink_total_tx"].values.astype(float)
        val = np.where(tot > 0, val / tot, 0.0)
    d = bleed["distance"].values

    def _denominator(sub):
        if group_col == "sink_type" and "n_sink_cells_total" in sub.columns:
            return int(sub["n_sink_cells_total"].iloc[0])
        return sub["sink_cell_row"].unique().size

    if groupby is None and direction == "sink":
        per_sink_totals = (bleed[["sink_type", "n_sink_cells_total"]]
                           .drop_duplicates()["n_sink_cells_total"].sum())
        keys = [(None, np.arange(len(bleed)), int(per_sink_totals))]
    elif groupby is None:
        keys = [(None, np.arange(len(bleed)),
                 bleed["sink_cell_row"].unique().size)]
    else:
        keys = []
        for k, sub in bleed.groupby(group_col):
            keys.append((k, sub.index.to_numpy(), _denominator(sub)))

    out = []
    for key, idx, denom in keys:
        if denom == 0:
            continue
        order = np.argsort(d[idx])
        d_sorted = d[idx][order]
        v_sorted = val[idx][order]
        cum = np.cumsum(v_sorted)
        pos = np.searchsorted(d_sorted, r_grid, side="right") - 1
        cum_at = np.where(pos >= 0, cum[np.clip(pos, 0, len(cum) - 1)], 0.0)
        row = {"r": r_grid, "cum_mean": cum_at / denom, "n_denom": denom}
        if groupby is not None or direction != "sink":
            row[group_col] = key if key is not None else "__all__"
        out.append(pd.DataFrame(row))
    if not out:
        return pd.DataFrame(columns=["r", "cum_mean", "n_denom"])
    return pd.concat(out, ignore_index=True)


def bleed_at_radius(
    bleed: pd.DataFrame,
    *,
    r: float = 10.0,
    direction: str = "sink",
    normalize: bool = False,
) -> pd.DataFrame:
    """Scalar class-balanced mean bleed counts per cell within ``r``, per group
    (sink_type if direction='sink', else source_type).

    Returns columns: r, direction, {group_col}, bleed_rate, n_cells, n_triples,
    bleed_sum. (cancer/method/version are the caller's to attach.)
    """
    if bleed.empty:
        return pd.DataFrame()
    group_col = {"sink": "sink_type", "source": "source_type"}[direction]

    val = bleed["eligible_counts"].values.astype(float)
    if normalize:
        tot = bleed["sink_total_tx"].values.astype(float)
        val = np.where(tot > 0, val / tot, 0.0)
    bleed = bleed.assign(_value=val)
    sub = bleed[bleed["distance"] <= r]

    if direction == "sink":
        cells_per_group = (bleed.groupby(group_col)["n_sink_cells_total"]
                           .first().rename("n_cells"))
    else:
        cells_per_group = (bleed.groupby(group_col)["sink_cell_row"]
                           .apply(lambda s: s.unique().size).rename("n_cells"))

    bleed_per_group = sub.groupby(group_col)["_value"].sum().rename("bleed_sum")
    counts_per_group = sub.groupby(group_col).size().rename("n_triples")
    out = (pd.concat([cells_per_group, bleed_per_group, counts_per_group], axis=1)
           .fillna({"bleed_sum": 0.0, "n_triples": 0})
           .reset_index())
    out["bleed_rate"] = out["bleed_sum"] / out["n_cells"].replace(0, np.nan)
    out["r"] = r
    out["direction"] = direction
    return out[["r", "direction", group_col,
                "bleed_rate", "n_cells", "n_triples", "bleed_sum"]]


# =============================================================================
# Null comparison: expression-matched random gene sets
# =============================================================================

def _draw_null_gene_set(
    src_markers: list, target_size: int, gene_to_idx: dict,
    expr_bin: np.ndarray, by_bin: dict, candidate_pool: list,
    rng: np.random.Generator,
) -> list:
    """Draw a null gene set of size ``target_size`` matching the expression-bin
    distribution of ``src_markers``, from genes that are not a marker of any
    type (``candidate_pool``)."""
    src_bins = [expr_bin[gene_to_idx[g]] for g in src_markers if g in gene_to_idx]
    if not src_bins:
        return []
    bin_fracs = pd.Series(src_bins).value_counts(normalize=True).to_dict()
    drawn = []
    for b, frac in bin_fracs.items():
        need = int(round(frac * target_size))
        pool = by_bin.get(b, [])
        if not pool or need == 0:
            continue
        take = min(need, len(pool))
        drawn.extend(rng.choice(pool, size=take, replace=False).tolist())
    if len(drawn) < target_size:
        remaining = [g for g in candidate_pool if g not in drawn]
        if remaining:
            top = rng.choice(remaining,
                             size=min(target_size - len(drawn), len(remaining)),
                             replace=False).tolist()
            drawn.extend(top)
    return drawn[:target_size]


def bleed_null_comparison(
    adata: AnnData,
    bleed: pd.DataFrame,
    markers: Dict[str, Set[str]],
    *,
    n_null_draws: int = 5,
    n_expr_bins: int = 20,
    seed: int = 42,
    r_grid: Optional[np.ndarray] = None,
    max_dist: float = 40.0,
) -> pd.DataFrame:
    """Compare true-marker bleed to expression-matched null bleed.

    For each (source, sink) pair in ``bleed``, draws ``n_null_draws`` null gene
    sets the same size as the pair's eligible set, matched to the source
    markers' expression-bin distribution, re-scans sink-cell counts under each
    draw, and returns cumulative curves for the true set and each null draw.

    ``adata`` must be the SAME spatial object (same gene axis and cell order)
    that produced ``bleed`` -- ``sink_cell_row`` indexes into it.

    Columns: r, cum_mean, variant ('true'|'null'), draw, sink_type. A pooled
    row uses sink_type='__all__'.
    """
    if r_grid is None:
        r_grid = np.linspace(0.0, max_dist, 200)
    if bleed.empty:
        return pd.DataFrame(columns=["r", "cum_mean", "variant", "draw",
                                     "sink_type"])

    X = adata.X
    if issparse(X):
        X = X.tocsr()
    X_csc = X.tocsc() if issparse(X) else X
    gene_to_idx = {g: i for i, g in enumerate(adata.var_names)}
    gene_names = np.array(adata.var_names)

    gene_total = (np.asarray(X.sum(axis=0)).flatten()
                  if issparse(X) else X.sum(axis=0))
    log_counts = np.log10(gene_total + 1.0)
    expr_bin = np.asarray(
        pd.qcut(log_counts, n_expr_bins, labels=False, duplicates="drop"))

    all_markers_union = set().union(*[markers[t] for t in markers
                                      if markers.get(t)])
    candidate_pool = [g for g in gene_names if g not in all_markers_union]
    by_bin = {}
    for g in candidate_pool:
        by_bin.setdefault(expr_bin[gene_to_idx[g]], []).append(g)

    def _sum_cols(cols):
        if len(cols) == 0:
            return np.zeros(X_csc.shape[0])
        sub = X_csc[:, cols]
        return (np.asarray(sub.sum(axis=1)).flatten()
                if issparse(sub) else sub.sum(axis=1))

    rng = np.random.default_rng(seed)

    def _cum_curve(values_arr, distances_arr, n_cells_group):
        order = np.argsort(distances_arr)
        d_sorted = distances_arr[order]
        v_sorted = values_arr[order]
        cum = np.cumsum(v_sorted)
        pos = np.searchsorted(d_sorted, r_grid, side="right") - 1
        cum_at = np.where(pos >= 0, cum[np.clip(pos, 0, len(cum) - 1)], 0.0)
        return cum_at / max(n_cells_group, 1)

    curve_rows = []
    sink_types = sorted(bleed["sink_type"].unique())
    n_per_sink = (bleed[["sink_type", "n_sink_cells_total"]]
                  .drop_duplicates().set_index("sink_type")
                  ["n_sink_cells_total"].to_dict())
    pooled_n = int(sum(n_per_sink.values()))

    # TRUE curves
    curve_rows.append(pd.DataFrame({
        "r": r_grid,
        "cum_mean": _cum_curve(bleed["eligible_counts"].values.astype(float),
                               bleed["distance"].values, pooled_n),
        "variant": "true", "draw": 0, "sink_type": "__all__"}))
    for sink in sink_types:
        sub = bleed[bleed["sink_type"] == sink]
        n = int(n_per_sink.get(sink, 0))
        curve_rows.append(pd.DataFrame({
            "r": r_grid,
            "cum_mean": _cum_curve(sub["eligible_counts"].values.astype(float),
                                   sub["distance"].values, n),
            "variant": "true", "draw": 0, "sink_type": sink}))

    # NULL curves
    pair_keys = bleed[["source_type", "sink_type"]].drop_duplicates().values
    size_by_pair = (bleed.groupby(["source_type", "sink_type"])
                    ["n_eligible_markers"].first().to_dict())

    for draw_i in range(n_null_draws):
        replacement = np.zeros(len(bleed), dtype=np.float32)
        for (src, sink) in pair_keys:
            size = int(size_by_pair[(src, sink)])
            null_genes = _draw_null_gene_set(
                list(markers[src]), size, gene_to_idx,
                expr_bin, by_bin, candidate_pool, rng)
            null_cols = [gene_to_idx[g] for g in null_genes if g in gene_to_idx]
            if not null_cols:
                continue
            counts_all = _sum_cols(null_cols)
            mask = ((bleed["source_type"].values == src) &
                    (bleed["sink_type"].values == sink))
            rows_for_pair = np.where(mask)[0]
            replacement[rows_for_pair] = counts_all[
                bleed["sink_cell_row"].values[rows_for_pair]]

        curve_rows.append(pd.DataFrame({
            "r": r_grid,
            "cum_mean": _cum_curve(replacement.astype(float),
                                   bleed["distance"].values, pooled_n),
            "variant": "null", "draw": draw_i, "sink_type": "__all__"}))
        for sink in sink_types:
            mask = bleed["sink_type"].values == sink
            if not mask.any():
                continue
            n = int(n_per_sink.get(sink, 0))
            curve_rows.append(pd.DataFrame({
                "r": r_grid,
                "cum_mean": _cum_curve(replacement[mask].astype(float),
                                       bleed["distance"].values[mask], n),
                "variant": "null", "draw": draw_i, "sink_type": sink}))

    return pd.concat(curve_rows, ignore_index=True)
